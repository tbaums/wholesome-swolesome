// ── Scheduled workouts (the new core unit) ────────────────────────────────────

/// A single planned workout for a specific date. Generated by the AI coach,
/// or created manually as a fallback.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ScheduledWorkout {
    pub id: String,
    /// YYYY-MM-DD — the date this workout is intended for.
    pub date: String,
    pub name: String,
    /// Coach's reasoning: which muscles, why this volume, recovery notes.
    #[serde(default)]
    pub rationale: String,
    #[serde(default)]
    pub source: WorkoutSource,
    pub exercises: Vec<ScheduledExercise>,
    /// ISO 8601 timestamp when the workout was generated/created.
    #[serde(default)]
    pub created_at: String,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
pub enum WorkoutSource {
    #[default]
    Coach,
    Manual,
}

/// Apple-Health-style HR zone budget. Used both as a coach prescription
/// (`target_zones`) and as a per-set actual (`zone_minutes`). Zone 1-5 maps
/// to the standard Apple Watch HR zones; we don't try to redefine them.
///
/// `minutes` is `f32`, not `u32`, because Apple Health samples HR continuously
/// and reports fractional zone time (e.g. `17.85` min in Z2). Legacy JSON
/// with integer values like `"minutes": 30` still deserializes — serde reads
/// integers into floats without complaint.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ZoneTarget {
    pub zone: u8,
    pub minutes: f32,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ScheduledExercise {
    /// `LibraryExercise.id` from /data/exercises.json. None = freeform name only.
    pub library_id: Option<String>,
    pub name: String,
    pub target_sets: u32,
    pub reps_min: u32,
    pub reps_max: u32,
    #[serde(default)]
    pub rest_seconds: u32,
    pub notes: Option<String>,
    #[serde(default)]
    pub target_duration_seconds: Option<u32>,
    /// Coach-prescribed HR zone breakdown for cardio. When `Some`, the
    /// session UI shows one input per zone instead of min × RPE.
    #[serde(default)]
    pub target_zones: Option<Vec<ZoneTarget>>,
}

// ── Session (in-progress / completed workout) ────────────────────────────────

/// Active workout being logged. `day_id`/`day_name` correspond to the
/// ScheduledWorkout id/name (kept for stored-history compatibility).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct WorkoutSession {
    pub id: String,
    pub date: String,
    pub day_id: String,
    pub day_name: String,
    pub exercise_logs: Vec<ExerciseLog>,
    pub is_complete: bool,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ExerciseLog {
    pub exercise_id: String,
    pub exercise_name: String,
    pub target_sets: u32,
    pub reps_min: u32,
    pub reps_max: u32,
    pub sets: Vec<SetLog>,
    #[serde(default)]
    pub target_duration_seconds: Option<u32>,
    /// Mirrors the prescription's `target_zones` so the session UI can
    /// render zone inputs without re-reading the original ScheduledExercise.
    #[serde(default)]
    pub target_zones: Option<Vec<ZoneTarget>>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
pub struct SetLog {
    pub set_number: u32,
    pub reps: u32,
    #[serde(alias = "weight_lbs")]
    pub weight: f32,
    pub completed: bool,
    #[serde(default)]
    pub completed_date: Option<String>,
    #[serde(default)]
    pub duration_seconds: Option<u32>,
    /// Actual minutes-per-zone the user logged for this set. Only ever
    /// populated for zone-shaped cardio sets; None for everything else.
    #[serde(default)]
    pub zone_minutes: Option<Vec<ZoneTarget>>,
}

