use serde::{Deserialize, Serialize};

// ── Legacy plan (kept for serde compatibility with existing sync state) ───────
//
// The app no longer uses a static 7-day plan. ScheduledWorkout replaces
// WorkoutDay as the unit of work. These types remain only so old state.json
// files deserialize without errors; new state never writes them.

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
pub struct WorkoutPlan {
    pub days: Vec<WorkoutDay>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct WorkoutDay {
    pub id: String,
    pub name: String,
    pub exercises: Vec<Exercise>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Exercise {
    pub id: String,
    pub name: String,
    pub target_sets: u32,
    pub reps_min: u32,
    pub reps_max: u32,
    #[serde(default)]
    pub category: ExerciseCategory,
    pub notes: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Default)]
pub enum ExerciseCategory {
    #[default]
    Main,
    Core,
    Cardio,
}

// ── User goals ────────────────────────────────────────────────────────────────

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct UserGoals {
    pub primary_goal: PrimaryGoal,
    pub sessions_per_week: u32,
    pub session_minutes: u32,
    /// Equipment identifiers (matches free-exercise-db `equipment` strings:
    /// "barbell", "dumbbell", "machine", "cable", "kettlebells", "body only",
    /// "bands", "exercise ball", etc.) Empty = assume full gym.
    pub equipment: Vec<String>,
    /// Free text: injuries, lifts to avoid, asymmetries, prior surgeries.
    pub avoid: String,
    /// Free text: anything else the coach should know.
    pub notes: String,
    /// Target aerobic minutes per week (sum of cardio session durations).
    /// None = no target set; coach falls back to generic prescription based on primary_goal.
    #[serde(default)]
    pub weekly_cardio_minutes_target: Option<u32>,
    /// Most recent VO2 max reading, manually entered or imported from an Apple Health screenshot.
    #[serde(default)]
    pub vo2_max_latest: Option<f32>,
    /// YYYY-MM-DD the VO2 max reading is from. Used to drop stale imports.
    #[serde(default)]
    pub vo2_max_updated: Option<String>,
    #[serde(default)]
    pub mobility_focus: FocusLevel,
    #[serde(default)]
    pub balance_focus: FocusLevel,
}

impl Default for UserGoals {
    fn default() -> Self {
        Self {
            primary_goal: PrimaryGoal::default(),
            sessions_per_week: 4,
            session_minutes: 60,
            equipment: vec![],
            avoid: String::new(),
            notes: String::new(),
            weekly_cardio_minutes_target: None,
            vo2_max_latest: None,
            vo2_max_updated: None,
            mobility_focus: FocusLevel::default(),
            balance_focus: FocusLevel::default(),
        }
    }
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Default)]
pub enum FocusLevel {
    Low,
    #[default]
    Standard,
    High,
}

impl FocusLevel {
    pub fn label(&self) -> &'static str {
        match self {
            Self::Low => "Low",
            Self::Standard => "Standard",
            Self::High => "High",
        }
    }
    pub fn all() -> &'static [FocusLevel] {
        &[Self::Low, Self::Standard, Self::High]
    }
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Default)]
pub enum PrimaryGoal {
    #[default]
    Hypertrophy,
    Strength,
    FatLoss,
    Endurance,
    GeneralFitness,
}

impl PrimaryGoal {
    pub fn label(&self) -> &'static str {
        match self {
            Self::Hypertrophy => "Hypertrophy",
            Self::Strength => "Strength",
            Self::FatLoss => "Fat loss",
            Self::Endurance => "Endurance",
            Self::GeneralFitness => "General fitness",
        }
    }
    pub fn all() -> &'static [PrimaryGoal] {
        &[
            Self::Hypertrophy,
            Self::Strength,
            Self::FatLoss,
            Self::Endurance,
            Self::GeneralFitness,
        ]
    }
}

