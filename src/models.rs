// ── Muscle group taxonomy ────────────────────────────────────────────────────
//
// free-exercise-db uses 17 muscle keys; the body heatmap renders 15 visual
// regions (chest, shoulders, biceps, triceps, forearms, abs, obliques, lats,
// mid-back, lower back, traps, glutes, quads, hamstrings, calves, plus
// neck/abductors/adductors as small extras). The same `Muscle` key drives both
// heatmap coloring and library filtering.

pub const ALL_MUSCLES: &[&str] = &[
    "chest",
    "shoulders",
    "biceps",
    "triceps",
    "forearms",
    "abdominals",
    "lats",
    "middle back",
    "lower back",
    "traps",
    "glutes",
    "quadriceps",
    "hamstrings",
    "calves",
    "abductors",
    "adductors",
    "neck",
];

/// Human-readable label for a free-exercise-db muscle key.
pub fn muscle_label(key: &str) -> &str {
    match key {
        "abdominals" => "Abs",
        "middle back" => "Mid back",
        "lower back" => "Lower back",
        "quadriceps" => "Quads",
        _ => key,
    }
}
